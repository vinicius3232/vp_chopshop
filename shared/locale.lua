local valid = { en = true, pt = true, es = true, fr = true, tr = true }

---@param key string
---@param ... any format args for string.format
---@return string
function L(key, ...)
    local lang = (Config and Config.Locale) or 'en'
    if not valid[lang] then lang = 'en' end
    local pack = Locales[lang] or Locales.en
    local str = pack[key] or Locales.en[key] or key
    if select('#', ...) > 0 then
        local ok, out = pcall(string.format, str, ...)
        return ok and out or str
    end
    return str
end

---@param code string|nil
---@return string
function VPChopLocaleErr(code)
    if not code then return L('notify_generic_error') end
    return L('err_' .. tostring(code))
end
